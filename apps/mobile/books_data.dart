enum BookCategory {
  hadith,    // الحديث
  fiqh,      // الفقه
  seerah,    // السيرة
  aqeedah,   // العقيدة
  adab,      // الآداب والأخلاق
  tazkiyah,  // التزكية
  quran,     // علوم القرآن
}

class BookChapter {
  final int index;
  final String titleAr;
  final List<BookPage> pages;
  final String? intro;

  const BookChapter({
    required this.index,
    required this.titleAr,
    required this.pages,
    this.intro,
  });

  int get totalPages => pages.length;
  int get estimatedMinutes => (pages.fold<int>(
        0,
        (sum, p) => sum + p.content.split(' ').length,
      ) ~/
      200)
      .clamp(1, 999);
}

class BookPage {
  final int index;
  final String content;
  final String? title;
  final bool isHadith;
  final String? hadithNumber;
  final String? source;

  const BookPage({
    required this.index,
    required this.content,
    this.title,
    this.isHadith = false,
    this.hadithNumber,
    this.source,
  });
}

class IslamicBook {
  final String id;
  final String titleAr;
  final String titleEn;
  final String authorAr;
  final String authorEn;
  final String descriptionAr;
  final String emoji;
  final BookCategory category;
  final List<BookChapter> chapters;
  final int publishYear; // hijri
  final String coverColor; // hex
  final String coverColor2;

  const IslamicBook({
    required this.id,
    required this.titleAr,
    required this.titleEn,
    required this.authorAr,
    required this.authorEn,
    required this.descriptionAr,
    required this.emoji,
    required this.category,
    required this.chapters,
    required this.publishYear,
    required this.coverColor,
    required this.coverColor2,
  });

  int get totalPages =>
      chapters.fold<int>(0, (sum, c) => sum + c.totalPages);

  int get estimatedReadingMinutes =>
      chapters.fold<int>(0, (sum, c) => sum + c.estimatedMinutes);

  String get categoryLabel => switch (category) {
        BookCategory.hadith => 'الحديث',
        BookCategory.fiqh => 'الفقه',
        BookCategory.seerah => 'السيرة',
        BookCategory.aqeedah => 'العقيدة',
        BookCategory.adab => 'الآداب',
        BookCategory.tazkiyah => 'التزكية',
        BookCategory.quran => 'علوم القرآن',
      };
}

